export const TRANSCRIPT = SEQUENCE.map((c) => c.text).join("\n\n")

const cumulativeChars: number[] = (() => {
  const total = TRANSCRIPT.length
  let acc = 0
  return SEQUENCE.map((c, i) => {
    acc += c.text.length + (i < SEQUENCE.length - 1 ? 2 : 0)
    return acc / total
  })
})()

export function chunkIdAtFraction(t: number): string | null {
  if (!Number.isFinite(t) || t < 0) return null
  for (let i = 0; i < cumulativeChars.length; i++) {
    if (t <= cumulativeChars[i]) return SEQUENCE[i].id
  }
  return SEQUENCE[SEQUENCE.length - 1].id
}
